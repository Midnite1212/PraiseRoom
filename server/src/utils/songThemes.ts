const MIN_LYRIC_KEYWORDS = 2;

const isLatinPhrase = (keyword: string): boolean => /^[a-z0-9' ]+$/.test(keyword);

const escapeRegExp = (value: string): string => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const matcherFor = (keywords: readonly string[]): RegExp => {
  const latin = keywords.filter(isLatinPhrase).map(escapeRegExp);
  const other = keywords.filter((keyword) => !isLatinPhrase(keyword)).map(escapeRegExp);
  const alternatives = [...other];
  if (latin.length > 0) {
    alternatives.push(`(?<![\\p{L}\\p{N}])(?:${latin.join('|')})(?![\\p{L}\\p{N}])`);
  }
  return new RegExp(alternatives.join('|'), 'gu');
};

const THEME_MATCHERS = SONG_THEMES.map(
  (theme) => [theme, matcherFor(THEME_KEYWORDS[theme])] as const
);

// Section labels and inline chords go first so a chord in the middle of a word leaves the word whole.
const searchableText = (text: string): string =>
  text
    .replace(/\{[^}]*\}/g, ' ')
    .replace(/\[[^\]]*\]/g, '')
    .toLowerCase()
    .replace(/[‘’ʼ`]/g, "'")
    .replace(/[^\p{L}\p{N}']+/gu, ' ')
    .trim();

const distinctMatches = (matcher: RegExp, text: string): number =>
  new Set(Array.from(text.matchAll(matcher), (match) => match[0])).size;

// A title names its theme outright; lyrics repeat, so they need two different keywords.
export const deriveSongThemes = (title: string, chordLyrics: string): SongTheme[] => {
  const titleText = searchableText(title);
  const lyricsText = searchableText(chordLyrics);
  return THEME_MATCHERS.filter(
    ([, matcher]) =>
      distinctMatches(matcher, titleText) > 0 ||
      distinctMatches(matcher, lyricsText) >= MIN_LYRIC_KEYWORDS
  ).map(([theme]) => theme);
};

export const mergeThemes = (existing: readonly string[], derived: readonly string[]): string[] =>
  Array.from(new Set([...existing, ...derived]));
